package aula01;

public class Calculadora {
    int operando1;
    int operando2;

    int adicao(){
        return operando1 + operando2;
    }

    int subtracao(){
        return operando1 - operando2;
    }

    int multiplicacao(){
        return operando1 * operando2;
    }

    int divisão(){
        return operando1 / operando2;
    }

}
